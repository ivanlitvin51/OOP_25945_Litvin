#pragma once

#include <cmath> // для функции std::sqrt (квадратный корень)

// ============================================================================
// Пространство имен для базовой (точной) реализации вычисления гипотенузы
// ============================================================================
namespace hypo_basic {

    // Шаблонная функция вычисления гипотенузы по формуле: sqrt(a^2 + b^2).
    // Использование шаблона (template <typename T>) позволяет функции принимать
    // любые числовые типы данных: int, float, double и др.
    template <typename T>
    double hypotenuse(T a, T b) {
        // Приводим аргументы к типу double, чтобы избежать целочисленного
        // переполнения при перемножении (a * a) и точно извлечь корень.
        double da = static_cast<double>(a);
        double db = static_cast<double>(b);

        return std::sqrt(da * da + db * db);
    }

} // namespace hypo_basic
