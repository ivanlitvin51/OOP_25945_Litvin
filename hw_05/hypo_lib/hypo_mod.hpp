#pragma once

#include "hypo.hpp"
#include <random> // для std::random_device, std::mt19937, std::uniform_*_distribution

// ============================================================================
// Пространство имен для модифицированной функции (с добавлением случайного бонуса)
// ============================================================================
namespace hypo_random {

    // Шаблонная функция вычисления гипотенузы со случайной модификацией:
    // 1. Сначала считает точную гипотенузу через hypo_basic::hypotenuse(a, b).
    // 2. С вероятностью 50% (бросок "монетки" 0 или 1) добавляет случайный бонус от 1.0 до 10.0.
    template <typename T>
    double hypotenuse(T a, T b) {
        // Считаем точную гипотенузу
        double result = hypo_basic::hypotenuse(a, b);

        // Статический генератор случайных чисел (std::mt19937) и источник энтропии (std::random_device).
        // Ключевое слово static гарантирует, что генератор инициализируется только один раз
        // при первом вызове функции, а не пересоздается заново при каждом вычислении.
        static std::random_device rd;
        static std::mt19937 gen(rd());

        // Распределение для подбрасывания монетки: возвращает 0 или 1 с вероятностью 50%
        static std::uniform_int_distribution<int> coin(0, 1);

        // Равномерное распределение вещественных чисел для бонуса от 1.0 до 10.0
        static std::uniform_real_distribution<double> bonus(1.0, 10.0);

        // Если выпал 0, прибавляем случайный бонус к результату
        if (coin(gen) == 0) {
            result += bonus(gen);
        }

        return result;
    }

} // namespace hypo_random
