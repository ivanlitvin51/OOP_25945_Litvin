#include <gtest/gtest.h>
#include <cmath>
#include "hypo.hpp"
#include "hypo_mod.hpp"

// ============================================================================
// 1. ТЕСТЫ БАЗОВОЙ ГИПОТЕНУЗЫ (hypo_basic::hypotenuse)
// ============================================================================

// Тест для целых чисел (типы int)
TEST(HypoBasicTest, IntegerArguments) {
    // Египетский треугольник 3-4-5
    EXPECT_DOUBLE_EQ(hypo_basic::hypotenuse(3, 4), 5.0);

    // Пифагорова тройка 6-8-10
    EXPECT_DOUBLE_EQ(hypo_basic::hypotenuse(6, 8), 10.0);

    // Пифагорова тройка 5-12-13
    EXPECT_DOUBLE_EQ(hypo_basic::hypotenuse(5, 12), 13.0);

    // Нулевые катеты
    EXPECT_DOUBLE_EQ(hypo_basic::hypotenuse(0, 0), 0.0);
}

// Тест для вещественных чисел (типы double - проверка шаблона 5.V)
TEST(HypoBasicTest, DoubleArguments) {
    // Катеты 2.5 и 6.0 -> гипотенуза sqrt(6.25 + 36) = sqrt(42.25) = 6.5
    EXPECT_DOUBLE_EQ(hypo_basic::hypotenuse(2.5, 6.0), 6.5);

    // Катеты 1.0 и 1.0 -> sqrt(2) ≈ 1.41421356...
    EXPECT_NEAR(hypo_basic::hypotenuse(1.0, 1.0), std::sqrt(2.0), 1e-9);
}

// ============================================================================
// 2. ТЕСТЫ МОДИФИЦИРОВАННОЙ ГИПОТЕНУЗЫ С РАНДОМОМ (hypo_random::hypotenuse)
// ============================================================================

// Проверяем, что при случайном бонусе результат всегда находится в допустимом диапазоне:
// [базовая_гипотенуза, базовая_гипотенуза + 10.0]
TEST(HypoRandomTest, RangeCheck) {
    const int a = 3;
    const int b = 4;
    const double base = 5.0; // hypo_basic::hypotenuse(3, 4)

    // Выполняем 100 вычислений со случайным бонусом
    for (int i = 0; i < 100; ++i) {
        double res = hypo_random::hypotenuse(a, b);

        // Результат не может быть меньше базовой гипотенузы
        EXPECT_GE(res, base);

        // Результат не может быть больше базовой гипотенузы + максимальный бонус (10.0)
        EXPECT_LE(res, base + 10.0 + 1e-9);
    }
}

// ============================================================================
// 3. ДЕМОНСТРАЦИЯ РАЗЛИЧИЯ ASSERT_ И EXPECT_ (Задание 5.III.4)
// ============================================================================
//
// ТЕОРЕТИЧЕСКАЯ РАЗНИЦА:
// - EXPECT_* (например, EXPECT_EQ, EXPECT_TRUE):
//     Некритическая (non-fatal) проверка. Если условие ложно, тест регистрирует
//     ошибку (FAILURE), но ПРОДОЛЖАЕТ выполнение следующих строк функции теста.
//     Это удобно, чтобы увидеть сразу все непрошедшие проверки за один запуск.
//
// - ASSERT_* (например, ASSERT_EQ, ASSERT_TRUE):
//     Критическая (fatal) проверка. Если условие ложно, тест регистрирует ошибку
//     и НЕМЕДЛЕННО ПРЕРЫВАЕТ выполнение ТЕКУЩЕЙ тестовой функции (вызывает return).
//     Последующие строки в этом тесте вообще не будут выполнены!
//     Это необходимо, когда дальнейшие действия бессмысленны или приведут к краху
//     (например, ASSERT_NE(ptr, nullptr) перед разыменованием указателя *ptr).
//
// Префикс DISABLED_ в Google Test временно отключает запуск теста при обычном
// тестировании, чтобы проект оставался зеленым (успешным).
//
// ЧТОБЫ УВИДЕТЬ ПРОВАЛЬНЫЙ ТЕСТ И РАЗНИЦУ:
// Запустите тесты с флагом:
//   .\build\tests\hypo_tests.exe --gtest_also_run_disabled_tests
// Или просто удалите приставку "DISABLED_" из названия теста ниже!
// ============================================================================

TEST(ExpectVsAssertDemo, DISABLED_FailingDemonstration) {
    std::cout << "\n--- НАЧАЛО ДЕМОНСТРАЦИИ EXPECT vs ASSERT ---\n";

    // 1. Пример с EXPECT_EQ (нефатальный сбой):
    // Намеренно ожидаем 999.0 вместо правильного 5.0
    std::cout << "[ШАГ 1] Выполняем заведомо ошибочный EXPECT_EQ...\n";
    EXPECT_DOUBLE_EQ(hypo_basic::hypotenuse(3, 4), 999.0);

    // ЭТА СТРОКА ВЫПОЛНИТСЯ, несмотря на то что EXPECT выше провалился!
    std::cout << "[ШАГ 2] Сообщение ПОСЛЕ упавшего EXPECT_EQ (тест продолжил работу!)\n";

    // 2. Пример с ASSERT_EQ (фатальный сбой):
    // Намеренно ожидаем 777.0 вместо правильного 5.0
    std::cout << "[ШАГ 3] Выполняем заведомо ошибочный ASSERT_EQ...\n";
    ASSERT_DOUBLE_EQ(hypo_basic::hypotenuse(3, 4), 777.0);

    // ЭТА СТРОКА УЖЕ НИКОГДА НЕ ВЫПОЛНИТСЯ, так как ASSERT прервал выполнение теста!
    std::cout << "[ШАГ 4] ЭТО СООБЩЕНИЕ НИКОГДА НЕ БУДЕТ НАПЕЧАТАНО!\n";
}
