#include <iostream>
#include <iomanip> // для std::fixed и std::setprecision (аккуратный вывод чисел)
#include "hypo.hpp"
#include "hypo_mod.hpp"

int main() {
    std::cout << "====================================================\n";
    std::cout << "   Лабораторная работа №5 (НГУ): CMake и Библиотеки \n";
    std::cout << "====================================================\n\n";

    // Устанавливаем вывод дробных чисел с 2 знаками после запятой
    std::cout << std::fixed << std::setprecision(2);

    // ------------------------------------------------------------------------
    // Демонстрация 1: Работа базовой функции hypo_basic с типом int (катеты 3 и 4)
    // ------------------------------------------------------------------------
    int a_int = 3;
    int b_int = 4;
    double res_int = hypo_basic::hypotenuse(a_int, b_int);

    std::cout << "[1] Базовая гипотенуза для int (катеты " << a_int << " и " << b_int << "):\n";
    std::cout << "    hypo_basic::hypotenuse(" << a_int << ", " << b_int << ") = "
              << res_int << " (ожидаем 5.00)\n\n";

    // ------------------------------------------------------------------------
    // Демонстрация 2: Работа базовой функции с типом double (шаблоны из задания 5.V)
    // ------------------------------------------------------------------------
    double a_dbl = 2.5;
    double b_dbl = 6.0;
    double res_dbl = hypo_basic::hypotenuse(a_dbl, b_dbl);

    std::cout << "[2] Базовая гипотенуза для double (катеты " << a_dbl << " и " << b_dbl << "):\n";
    std::cout << "    hypo_basic::hypotenuse(" << a_dbl << ", " << b_dbl << ") = "
              << res_dbl << " (ожидаем 6.50)\n\n";

    // ------------------------------------------------------------------------
    // Демонстрация 3: Работа модифицированной функции hypo_random (со случайным бонусом)
    // ------------------------------------------------------------------------
    std::cout << "[3] Модифицированная гипотенуза с рандомом (бонус 1..10 с шансом 50%)\n";
    std::cout << "    Выполним 6 вычислений для катетов " << a_int << " и " << b_int << ":\n";

    for (int i = 1; i <= 6; ++i) {
        double res_rand = hypo_random::hypotenuse(a_int, b_int);
        std::cout << "    Запуск #" << i << ": " << res_rand;

        // Если результат больше базовой гипотенузы, значит сработал бонус
        if (res_rand > res_int + 0.001) {
            std::cout << " -> сработал бонус! (+" << (res_rand - res_int) << ")";
        } else {
            std::cout << " -> бонус не выпал (точное значение 5.00)";
        }
        std::cout << "\n";
    }

    std::cout << "\nПрограмма успешно выполнена!\n";
    return 0;
}
